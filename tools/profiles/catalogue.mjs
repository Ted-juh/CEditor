// catalogue.mjs — the list of device profiles in docs/device-profile-library.md, from the profiles.
//
//   node tools/profiles/catalogue.mjs            # rewrite the catalogue between its markers
//   node tools/profiles/catalogue.mjs --check    # fail if the page no longer matches the profiles
//
// A hand-kept list of eighty profiles goes stale the first time one is added, and a stale list is
// worse than none: it is believed. So the page's catalogue is written from CE/profiles/test itself,
// and profileCatalogue.test.js fails when the two disagree.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { readCommitted } from '../scripts/readCommitted.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '../..');
const PROFILE_DIR = path.join(REPO, 'CE/profiles/test');
export const PAGE = path.join(REPO, 'docs/device-profile-library.md');
const START = '<!-- catalogue:start (generated by tools/profiles/catalogue.mjs; do not edit by hand) -->';
const END = '<!-- catalogue:end -->';

/** How a profile talks to its instrument, from its recipes rather than from its name. */
function kindOf(profile) {
  const kinds = new Set((profile.messageRecipes ?? []).map((r) => r.kind));
  if (kinds.has('sysex') && (profile.dumpDefinitions ?? []).length) return 'SysEx parameters and dumps';
  if (kinds.has('sysex')) return 'SysEx parameters';
  if ([...kinds].every((k) => k === 'cc')) return 'Control changes';
  return [...kinds].sort().map((k) => k.toUpperCase()).join(', ');
}

function madeBy(profile) {
  const note = (profile.authoringNotes ?? [])[0] ?? '';
  const tool = /tools\/profiles\/[\w/.-]+\.mjs/.exec(note)?.[0];
  if (tool) return `\`${tool.replace('tools/profiles/', '')}\``;
  // The DPD's own profiles carry the document they were emitted from; the rest predate these tools.
  return profile.dpdSource ? 'Device Profile Designer' : 'before these tools';
}

export function catalogue() {
  const profiles = readdirSync(PROFILE_DIR)
    .filter((f) => f.endsWith('.ceditor-device.json'))
    .map((f) => JSON.parse(readFileSync(path.join(PROFILE_DIR, f), 'utf8')))
    .filter((p) => p.family !== 'Internal Test');
  const byMaker = new Map();
  for (const p of profiles) byMaker.set(p.manufacturer ?? '—', [...(byMaker.get(p.manufacturer ?? '—') ?? []), p]);

  const lines = [START, ''];
  const total = profiles.length;
  const parameters = profiles.reduce((n, p) => n + (p.parameters ?? []).length, 0);
  lines.push(`${total} profiles, ${parameters.toLocaleString('en-US')} parameters between them; none yet checked on a real instrument.`, '');
  for (const maker of [...byMaker.keys()].sort()) {
    const list = byMaker.get(maker).sort((a, b) => (a.family ?? '').localeCompare(b.family ?? '') || a.name.localeCompare(b.name));
    lines.push(`### ${maker} (${list.length})`, '');
    lines.push('| Profile | Instrument | Family | Talks in | Parameters | Read from | Made by |');
    lines.push('|---|---|---|---|---:|---|---|');
    for (const p of list) {
      const source = (p.sources ?? [])[0]?.title ?? '—';
      lines.push(`| \`${p.id}\` | ${p.name} | ${p.family || '—'} | ${kindOf(p)} | ${(p.parameters ?? []).length.toLocaleString('en-US')} | ${source} | ${madeBy(p)} |`);
    }
    lines.push('');
  }
  lines.push(END);
  return lines.join('\n');
}

export function render(page) {
  const from = page.indexOf(START);
  const to = page.indexOf(END);
  if (from < 0 || to < from) throw new Error(`${path.relative(REPO, PAGE)} has no catalogue markers`);
  return `${page.slice(0, from)}${catalogue()}${page.slice(to + END.length)}`;
}

function main() {
  const current = readCommitted(PAGE);
  const next = render(current.replace(/\r\n/g, '\n'));
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('Stale: docs/device-profile-library.md — run: node tools/profiles/catalogue.mjs');
      process.exitCode = 1;
    } else {
      console.log('The profile catalogue is up to date.');
    }
    return;
  }
  writeFileSync(PAGE, next);
  console.log(`Wrote the catalogue in ${path.relative(REPO, PAGE)}`);
  // The page ships inside the program's help, so the bundle carries a copy of it.
  if (next !== current) console.log('The page is in the in-app help: now run `npm run docs:help` in CE/web.');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
