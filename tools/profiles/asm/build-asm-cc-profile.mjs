// build-asm-cc-profile.mjs — an ASM owner's manual's CC chart (tables/<name>.json) and a layout
// (synths/<name>.mjs) -> a CEditor device profile of control changes.
//
// What it takes as settled: a row is its controller, grouped by its module, its value the
// controller's 0 - 127 (the chart prints no ranges); the System and Global module's controllers
// that are not the instrument's sound (bank select, the wheel, the pedals, master volume, all notes
// off) are left out by name.

import { camel, stringifyProfile } from '../roland/build-profile.mjs';

const hex = (n) => n.toString(16).toUpperCase().padStart(2, '0');
const STANDARD = /^(?:Bank select (?:MSB|LSB)|Modulation wheel\.?|Mod Wheel|Master Volume|Expression pedal|Sustain pedal|All notes off)$/i;

export function buildAsmCcProfile(data, layout) {
  const left = [];
  const ids = new Set();
  const unique = (id) => { let out = id; for (let n = 2; ids.has(out); n++) out = `${id}${n}`; ids.add(out); return out; };
  const recipes = new Map();
  const parameters = [];
  for (const r of data.rows) {
    if (STANDARD.test(r.name)) { left.push(`CC ${r.cc} ${r.name}`); continue; }
    const recipe = { id: `cc${r.cc}`, kind: 'cc', channel: '$channel', controller: r.cc, value: '$encodedValue' };
    recipes.set(recipe.id, recipe);
    parameters.push({
      id: unique(`${camel(r.module)}.${camel(r.name)}`),
      name: r.name,
      group: r.module,
      access: { canRead: false, canWrite: true, realtimeSafe: true, source: 'singleParameter' },
      messageRecipe: recipe.id,
      type: 'integer',
      range: { min: 0, max: 127 },
      default: 0,
      display: { mode: 'number', unit: '', shortLabel: camel(r.name) },
      normalization: { mode: 'linear' },
      encoding: { type: 'u7' },
      sendPolicy: { mode: 'continuous', coalesce: true, minIntervalMs: 0, sendFinalOnRelease: true },
      ui: { preferredComponent: /Level|Vol|Attack|Decay|Sustain|Release|Cutoff|Res|Amt|Gain|Dry\/Wet|Depth/i.test(r.name) ? 'Slider' : 'Knob' },
    });
  }
  const notes = [];
  if (left.length) notes.push(`Left out, the bank select, wheel, pedal, volume and all notes off controllers: ${left.join(', ')}.`);
  const variables = { channel: 1 };
  const tests = [parameters[0], parameters.at(-1)].map((p) => {
    const r = recipes.get(p.messageRecipe);
    return { name: `${p.group} ${p.name} = 100 (CC ${r.controller})`, parameter: p.id, value: 100, expectedHex: [0xb0, r.controller, 100].map(hex).join(' ') };
  });
  const doc = data.sources[0];
  return {
    schemaVersion: 1,
    profileVersion: layout.profileVersion ?? '0.1.0',
    minCEditorVersion: '0.9.0',
    id: layout.id,
    name: layout.name,
    manufacturer: 'ASM',
    family: layout.family,
    status: 'experimental',
    trust: 'local',
    description: layout.description,
    sources: [{ type: 'manual', title: doc.title, notes: `MIDI CC chart, sorted by module (page${layout.pages.length > 1 ? 's' : ''} ${layout.pages.join(', ')} of the PDF), read by tools/profiles/asm/read-asm-cc.mjs from ${doc.file} (sha256 ${doc.sha256}), ${doc.url}. Not yet checked against the instrument itself.` }],
    testedWith: [],
    authoringNotes: [
      'Generated by tools/profiles/asm/make-profiles.mjs; edit the layout in tools/profiles/asm/synths/, not this file.',
      'Every parameter is a row of the manual\'s MIDI CC chart, sent as that control change on the channel variable, its value the controller\'s 0 - 127: the chart prints no ranges. The instrument takes them when its Param RX (MIDI settings) is CC. Nothing here has been sent to a real instrument yet.',
      ...(layout.notes ?? []),
      ...notes,
    ],
    variables,
    coverage: {
      singleParameterWrite: 'complete-for-the-manual\'s-CC-chart',
      realtimeEditing: 'complete-for-the-manual\'s-CC-chart',
      editBufferDumpRequest: 'notImplemented',
      editBufferDumpParse: 'notImplemented',
      bankDump: 'notImplemented',
      inboundControllers: 'the instrument sends these controllers when its Param TX is CC',
      verifiedOnHardware: false,
    },
    timing: { minDelayBetweenMessagesMs: 0 },
    messageRecipes: [...recipes.values()].sort((a, b) => a.controller - b.controller),
    parameters,
    tests,
  };
}

export { stringifyProfile };
