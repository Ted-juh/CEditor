// build-vermona-profile.mjs — a Vermona guide's transcription (tables/<name>.json) and its layout
// (synths/<name>.mjs) -> a CEditor device profile.
//
// What it takes as settled, from the guide:
//   - the Mono Lancet '15's switches: each its controller, a choice of the two bands the guide's
//     sentence gives every one (`0..63 means OFF; 64..127 means ON`), a band's first value sent, its
//     default the factory setting printed beside it;
//   - the Kick Lancet's: each its controller, a choice of the values printed under it, its default
//     the one marked `(factory default)`;
//   - on the channel variable: channel 1, or the channel of the note sent after powering on with
//     TRIG held.

import { camel, stringifyProfile } from '../roland/build-profile.mjs';

const hex = (n) => n.toString(16).toUpperCase().padStart(2, '0');

/** `0..63 means OFF; 64..127 means ON` -> [{ value: 0, label: 'OFF' }, { value: 64, label: 'ON' }]. */
export function bandsOf(meaning) {
  return [...String(meaning).matchAll(/(\d+)\.\.\d+ means (\w+)/g)].map((m) => ({ value: Number(m[1]), label: m[2] }));
}

export function buildVermonaProfile(data, layout) {
  const parameters = [];
  const recipes = [];
  const choice = (base, choices, def) => ({ ...base, type: 'choice', default: def, choices, display: { mode: 'choice', shortLabel: base.id.split('.').pop() }, normalization: { mode: 'choiceIndex' }, encoding: { type: 'u7' }, sendPolicy: { mode: 'onCommit', coalesce: true }, ui: { preferredComponent: choices.length === 2 ? 'ToggleButton' : 'RadioButtonGroup' } });
  // Where the guide prints a parameter: its page, where the table was read from one page alone (the
  // Mono Lancet's), or the page the reader found it on (the Kick Lancet's, its guide read whole).
  const pages = data.source.pages;
  const source = pages && pages[0] === pages[1] ? { source: { page: pages[0] } } : {};
  const sourceOf = (t) => (t.page ? { source: { page: t.page } } : source);
  if (data.switches) {
    const bands = bandsOf(data.switches.meaning);
    if (bands.length !== 2) throw new Error(`the switches' meaning is not read: ${data.switches.meaning}`);
    for (const r of data.switches.rows) {
      const id = `cc${hex(r.cc)}`;
      recipes.push({ id, kind: 'cc', channel: '$channel', controller: r.cc });
      const choices = bands.map((b) => ({ id: camel(b.label), label: b.label, value: b.value }));
      parameters.push(choice({ id: `midi.${camel(r.name)}`, name: r.name, group: 'MIDI', ...source, description: `CC ${r.cc}: ${r.description} Factory setting: ${r.factory}.`, access: { canRead: false, canWrite: true, realtimeSafe: true, source: 'singleParameter' }, messageRecipe: id }, choices, camel(r.factory)));
    }
  }
  for (const t of data.values ?? []) {
    const id = `cc${hex(t.cc)}`;
    recipes.push({ id, kind: 'cc', channel: '$channel', controller: t.cc });
    const choices = t.values.map((v) => ({ id: camel(v.label.replace(/\s*\(factory default\)/, '')), label: v.label.replace(/\s*\(factory default\)/, ''), value: v.value }));
    const def = t.values.find((v) => /\(factory default\)/.test(v.label));
    parameters.push(choice({ id: `inputs.${camel(t.jack)}`, name: `${t.jack} input`, group: 'Inputs', ...sourceOf(t), description: `CC ${t.cc}: what the ${t.jack} jack does. ${t.values.map((v) => `${v.value}: ${v.label} — ${v.description}`).join(' ')}`, access: { canRead: false, canWrite: true, realtimeSafe: true, source: 'singleParameter' }, messageRecipe: id }, choices, def ? choices[t.values.indexOf(def)].id : choices[0].id));
  }
  const tests = parameters.map((p) => ({ name: `${p.name} = ${p.choices.at(-1).id}`, parameter: p.id, value: p.choices.at(-1).id, expectedHex: ['B0', hex(recipes.find((r) => r.id === p.messageRecipe).controller), hex(p.choices.at(-1).value)].join(' ') }));
  const doc = data.source;
  return {
    schemaVersion: 1,
    profileVersion: layout.profileVersion ?? '0.1.0',
    minCEditorVersion: '0.9.0',
    id: layout.id,
    name: layout.name,
    manufacturer: 'Vermona',
    family: layout.family,
    status: 'experimental',
    trust: 'local',
    description: layout.description,
    sources: [{ type: 'manual', title: doc.title, notes: `The guide's MIDI control change table${doc.pages ? ` (PDF page ${doc.pages[0]})` : 's'}, read by tools/profiles/vermona/read-vermona.mjs from ${doc.file} (sha256 ${doc.sha256}), ${doc.url}, linked from ${doc.linkedFrom}. Not yet checked against the instrument itself.` }],
    testedWith: [],
    authoringNotes: [
      'Generated by tools/profiles/vermona/make-profiles.mjs; edit the layout in tools/profiles/vermona/synths/, not this file.',
      `Every parameter is a control change the guide gives, sent on the channel variable: the instrument receives on channel 1 until it is powered on with TRIG held and sent a note, whose channel it stores. ${data.switches ? `Each is a switch, "${data.switches.meaning}" for every one, as the guide says; a factory reset puts them back.` : 'Each sets what an input jack does, a value the guide prints a line for.'} The guide gives no controller for the sound's own knobs. Nothing here has been sent to a real instrument yet.`,
    ],
    variables: { channel: 1 },
    coverage: {
      singleParameterWrite: `complete-for-the-guide's-control-changes: ${parameters.length}`,
      realtimeEditing: 'complete-for-the-guide\'s-control-changes',
      editBufferDumpRequest: 'notImplemented',
      editBufferDumpParse: 'notImplemented',
      bankDump: 'notImplemented',
      inboundControllers: 'none: the instrument has MIDI IN and MIDI THRU only',
      verifiedOnHardware: false,
    },
    timing: { minDelayBetweenMessagesMs: 0 },
    messageRecipes: recipes,
    parameters,
    tests,
  };
}

export { stringifyProfile };
