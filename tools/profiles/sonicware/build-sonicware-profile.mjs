// build-sonicware-profile.mjs — a Sonicware transcription (tables/<name>.json) and a layout
// (synths/<name>.mjs) -> a CEditor device profile.
//
// What it takes as settled, from the chart:
//   - a row is its controller, its name the chart's remark, its group the block it is in (`(TRACK)`,
//     `(FILTER)`); a row the chart marks not recognized (× under Recognized) is left out, the
//     instrument only sending it;
//   - the chart prints no values: each is 0 - 127;
//   - a block is on the channel the layout says the chart gives it (the pattern's, the project's, a
//     track's), the channel variable otherwise;
//   - the wheel, the pedals and the channel mode messages are left out.

import { camel, stringifyProfile } from '../roland/build-profile.mjs';

const hex = (n) => n.toString(16).toUpperCase().padStart(2, '0');

export const PERFORMANCE = /^(?:※\s*)?(?:Modulation Wheel|Hold Pedal.*|Sustain.*|ALL SOUND OFF|ALL NOTES OFF|RESET ALL CONTROLLERS)$/i;

/** A block's label -> its group: the word in brackets (`Control *2 Change (TRACK)` -> `Track`). */
export const groupOf = (block) => {
  const m = /[(（]([^)）]+)[)）]/.exec(block ?? '');
  if (!m) return 'Global';
  return m[1].replace(/\s+/g, ' ').replace(/\s*\/\s*/g, '/').trim().toLowerCase().replace(/(^|[\s/])([a-z])/g, (s, a, b) => a + b.toUpperCase());
};

export function buildSonicwareProfile(data, layout) {
  const notes = [];
  const left = [];
  const sendOnly = [];
  const ids = new Set();
  const unique = (id) => { let out = id; for (let n = 2; ids.has(out); n++) out = `${id}${n}`; ids.add(out); return out; };
  const recipes = new Map();
  const parameters = [];
  const variables = { channel: 1, ...(layout.variables ?? {}) };
  const twice = [];
  for (const r of data.rows) {
    const name = r.name.replace(/\s*※\s*$/, '').replace(/^※\s*/, '');
    if (PERFORMANCE.test(name)) { left.push(`CC ${r.cc} ${name}`); continue; }
    if (r.recognized === '×') { sendOnly.push(`CC ${r.cc} ${name}`); continue; }
    const group = groupOf(r.block);
    const variable = layout.channelOf?.(group, name) ?? 'channel';
    const id = `cc${r.cc}${variable === 'channel' ? '' : variable.replace(/Channel$/, '').replace(/^./, (c) => c.toUpperCase())}`;
    if (recipes.has(id)) { twice.push(`CC ${r.cc} ${name}`); continue; }
    const recipe = { id, kind: 'cc', channel: `$${variable}`, controller: r.cc, value: '$encodedValue' };
    recipes.set(id, recipe);
    const label = name.replace(/\s+/g, ' ');
    parameters.push({
      id: unique(`${camel(group)}.${camel(label.toLowerCase())}`),
      name: label,
      group,
      description: `CC ${r.cc}${variable === 'channel' ? '' : `, on ${variable}`}.${r.recognized ? '' : ' The chart prints no mark under Recognized for it.'}`,
      access: { canRead: false, canWrite: true, realtimeSafe: true, source: 'singleParameter' },
      messageRecipe: id,
      type: 'integer',
      range: { min: 0, max: 127 },
      default: 0,
      display: { mode: 'number', unit: '', shortLabel: camel(label.toLowerCase()) },
      normalization: { mode: 'linear' },
      encoding: { type: 'u7' },
      sendPolicy: { mode: 'continuous', coalesce: true, minIntervalMs: 0, sendFinalOnRelease: true },
      ui: { preferredComponent: /LEVEL|ATTACK|DECAY|SUSTAIN|RELEASE|AMOUNT|DEPTH|MIX|CUTOFF|FREQ|RESO|SEND/i.test(label) ? 'Slider' : 'Knob' },
    });
  }
  if (twice.length) notes.push(`Rows on a controller already laid out, on the same channel, named here, not laid out: ${twice.join(', ')}.`);
  if (sendOnly.length) notes.push(`Left out, controllers the chart marks sent and not recognized: ${sendOnly.join(', ')}.`);
  if (left.length) notes.push(`Left out, the wheel, the pedals and the channel mode messages: ${left.join(', ')}.`);

  const picks = [...new Set([parameters[0], parameters.at(-1)].filter(Boolean))];
  const tests = picks.map((p) => {
    const r = recipes.get(p.messageRecipe);
    const status = 0xb0 + variables[r.channel.slice(1)] - 1;
    return { name: `${p.group} ${p.name} = 100 (CC ${r.controller})`, parameter: p.id, value: 100, expectedHex: [status, r.controller, 100].map(hex).join(' ') };
  });
  const doc = data.sources[0];
  return {
    schemaVersion: 1,
    profileVersion: layout.profileVersion ?? '0.1.0',
    minCEditorVersion: '0.9.0',
    id: layout.id,
    name: layout.name,
    manufacturer: 'Sonicware',
    family: layout.family,
    status: 'experimental',
    trust: 'local',
    description: layout.description,
    sources: [{ type: 'manual', title: doc.title, notes: `MIDI implementation chart read by tools/profiles/sonicware/read-sonicware-chart.mjs from ${doc.file} (sha256 ${doc.sha256}), ${doc.url}. Not yet checked against the instrument itself.` }],
    testedWith: [],
    authoringNotes: [
      'Generated by tools/profiles/sonicware/make-profiles.mjs; edit the layout in tools/profiles/sonicware/synths/, not this file.',
      'Every parameter is a control change the chart marks recognized, its name the chart\'s remark, sent on the channel of its block. The chart prints no values: each is 0 - 127. Nothing here has been sent to a real instrument yet.',
      ...(layout.notes ?? []),
      ...notes,
    ],
    variables,
    coverage: {
      singleParameterWrite: 'complete-for-the-MIDI-chart',
      realtimeEditing: 'complete-for-the-MIDI-chart',
      editBufferDumpRequest: 'notImplemented',
      editBufferDumpParse: 'notImplemented',
      bankDump: 'notImplemented',
      inboundControllers: 'the instrument sends the controllers its chart marks transmitted',
      verifiedOnHardware: false,
    },
    timing: { minDelayBetweenMessagesMs: 0 },
    messageRecipes: [...recipes.values()].sort((a, b) => a.channel.localeCompare(b.channel) || a.controller - b.controller),
    parameters,
    tests,
  };
}

export { stringifyProfile };
