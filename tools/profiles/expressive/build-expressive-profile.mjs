// build-expressive-profile.mjs — an Expressive E transcription (tables/<name>.json) and a layout
// (synths/<name>.mjs) -> a CEditor device profile.
//
// What it takes as settled, from the chart's control table:
//   - a row the chart marks Recognized is that controller, named as printed, its range the one its
//     remarks print (`range: [0-127]`), 0 - 127 where they print none;
//   - it is sent on the channel its remarks name (`Master Channel (channel 1)`: the MPE master
//     channel, the channel variable);
//   - the wheel and the pedals, bank select, aftertouch and the MPE+ resolution byte are the
//     player's, not settings, and are left out; so is a row the chart marks not recognized, named.

import { camel, stringifyProfile } from '../roland/build-profile.mjs';

const hex = (n) => n.toString(16).toUpperCase().padStart(2, '0');

export const PERFORMANCE = /^(?:Bank Select.*|Modulation Wheel.*|Pedal \d+|Aftertouch|MPE\+ .*|Data Entry.*|(?:Non-)?Registered Parameter Number.*|All Sound Off|Reset All Controllers|Local Control.*|All Notes Off|Omni Mode.*|Mono Mode.*|Poly Mode.*)$/i;

/** `range: [0-127]` in a row's remarks -> { lo, hi }, or null. */
export const rangeOf = (remarks) => {
  const m = /range:\s*\[(\d+)\s*-\s*(\d+)\]/.exec(remarks ?? '');
  return m ? { lo: Number(m[1]), hi: Number(m[2]) } : null;
};

export function buildExpressiveProfile(data, layout) {
  const notes = [];
  const left = [];
  const unrecognized = [];
  const recipes = new Map();
  const parameters = [];
  for (const r of data.rows) {
    if (!r.name) continue;
    if (PERFORMANCE.test(r.name)) { if (r.recognized === 'Yes') left.push(`CC ${r.cc} ${r.name}`); continue; }
    if (r.recognized !== 'Yes') { unrecognized.push(`CC ${r.cc} ${r.name}`); continue; }
    const range = rangeOf(r.remarks) ?? { lo: 0, hi: 127 };
    const group = layout.groupOf(r.name);
    const recipe = { id: `cc${r.cc}`, kind: 'cc', channel: '$channel', controller: r.cc, value: '$encodedValue' };
    recipes.set(recipe.id, recipe);
    parameters.push({
      id: `${camel(group)}.${camel(r.name.toLowerCase())}`,
      name: r.name,
      group,
      description: `CC ${r.cc}. Printed: ${r.remarks || 'no remarks'}.${r.transmitted === 'Yes' ? ' The instrument sends it too.' : ''}`,
      access: { canRead: false, canWrite: true, realtimeSafe: true, source: 'singleParameter' },
      messageRecipe: recipe.id,
      type: 'integer',
      range: { min: range.lo, max: range.hi },
      default: range.lo,
      display: { mode: 'number', unit: '', shortLabel: camel(r.name.toLowerCase()) },
      normalization: { mode: 'linear' },
      encoding: { type: 'u7' },
      sendPolicy: { mode: 'continuous', coalesce: true, minIntervalMs: 0, sendFinalOnRelease: true },
      ui: { preferredComponent: /gain|mix/i.test(r.name) ? 'Slider' : 'Knob' },
    });
  }
  if (left.length) notes.push(`Left out, the wheel, the pedals, bank select and the MPE+ resolution byte, which are the player's: ${left.join(', ')}.`);
  if (unrecognized.length) notes.push(`Left out, rows the chart marks not recognized: ${unrecognized.join(', ')}.`);

  const variables = { channel: 1 };
  const tests = [...new Set([parameters[0], parameters.at(-1)])].map((p) => {
    const r = recipes.get(p.messageRecipe);
    return { name: `${p.group} ${p.name} = ${p.range.max} (CC ${r.controller})`, parameter: p.id, value: p.range.max, expectedHex: [0xb0, r.controller, p.range.max].map(hex).join(' ') };
  });
  const doc = data.sources[0];
  return {
    schemaVersion: 1,
    profileVersion: layout.profileVersion ?? '0.1.0',
    minCEditorVersion: '0.9.0',
    id: layout.id,
    name: layout.name,
    manufacturer: 'Expressive E',
    family: layout.family,
    status: 'experimental',
    trust: 'local',
    description: layout.description,
    sources: [{ type: 'manual', title: doc.title, notes: `The MIDI implementation chart's control table (PDF pages ${layout.pages.join(', ')}) read by tools/profiles/expressive/import-expressive.mjs from ${doc.file} (sha256 ${doc.sha256}), ${doc.url}. Not yet checked against the instrument itself.` }],
    testedWith: [],
    authoringNotes: [
      'Generated by tools/profiles/expressive/make-profiles.mjs; edit the layout in tools/profiles/expressive/synths/, not this file.',
      'Every parameter is a controller the chart marks Recognized, with the name and range it prints, sent on the channel variable. Nothing here has been sent to a real instrument yet.',
      ...(layout.notes ?? []),
      ...notes,
    ],
    variables,
    coverage: {
      singleParameterWrite: 'complete-for-the-MIDI-implementation-chart',
      realtimeEditing: 'complete-for-the-MIDI-implementation-chart',
      editBufferDumpRequest: 'notImplemented',
      editBufferDumpParse: 'notImplemented',
      bankDump: 'notImplemented',
      inboundControllers: 'the instrument sends the controllers its chart marks Transmitted',
      verifiedOnHardware: false,
    },
    timing: { minDelayBetweenMessagesMs: 0 },
    messageRecipes: [...recipes.values()].sort((a, b) => a.controller - b.controller),
    parameters,
    tests,
  };
}

export { stringifyProfile };
