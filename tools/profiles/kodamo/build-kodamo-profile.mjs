// build-kodamo-profile.mjs — the MASK1 manual's MIDI implementation (tables/<name>.json) and its
// layout (synths/<name>.mjs) -> a CEditor device profile.
//
// What it takes as settled, from the manual:
//   - a controller it says is `Mapped to` a voice parameter (`Mapped to Filter > CUTF`) is that
//     parameter, sent 0 - 127 on the channel variable, grouped by the page it names; `(middle is 64)`
//     is its default; the mask's 512 values are four controllers of 128 (`(0-127 range)` …), laid out
//     as printed; CC 10's pan, which no page shows, is laid out too;
//   - the manual gives no values for the settings that are lists (filter mode, LFO wave and
//     destination, play mode, FX and arp type): they are sent 0 - 127, the list named in the manual's
//     chapters;
//   - left out, and named: bank select, the performance controllers (mod wheel, sustain) and the
//     channel mode messages (all sound off, all controllers off, all notes off, mono and poly mode).

import { camel, stringifyProfile } from '../roland/build-profile.mjs';

const hex = (n) => n.toString(16).toUpperCase().padStart(2, '0');
const LEFT = /^(?:Bank select|Modulation wheel|Sustain pedal|All sound off|All controllers off|All notes off|Mono mode|Poly mode)\b/;

/** `Mapped to Osc1 (Env) > L` -> Osc1 (Env); `Mapped to OSC1 > START` -> Osc1. */
export function pageOf(remark) {
  const m = /^Mapped to (.+?) >/.exec(remark);
  return m ? m[1].replace(/^OSC(\d)/, 'Osc$1') : null;
}

export function buildKodamoProfile(data, layout) {
  const recipes = new Map();
  const parameters = [];
  const left = [];
  for (const row of data.rows) {
    if (LEFT.test(row.name)) { left.push(`${row.name} (CC ${row.cc})`); continue; }
    const group = pageOf(row.remark) ?? 'General';
    const id = `cc${hex(row.cc)}`;
    recipes.set(id, { id, kind: 'cc', channel: '$channel', controller: row.cc });
    parameters.push({
      id: `${camel(group)}.${camel(row.name)}`, name: row.name, group,
      description: `CC ${row.cc}: ${row.name}; ${row.remark}.`.replace(/\.\.$/, '.'),
      access: { canRead: false, canWrite: true, realtimeSafe: true, source: 'singleParameter' }, messageRecipe: id,
      type: 'integer', range: { min: 0, max: 127 }, default: /middle is 64/.test(row.remark) ? 64 : 0,
      display: { mode: 'number', unit: '', shortLabel: camel(row.name) }, normalization: { mode: 'linear' }, encoding: { type: 'u7' },
      sendPolicy: { mode: 'continuous', coalesce: true, minIntervalMs: 0, sendFinalOnRelease: true }, ui: { preferredComponent: 'Knob' },
    });
  }
  const tests = [parameters[0], parameters.find((p) => p.default === 64), parameters.find((p) => /MASK \(384-511 range\)/.test(p.description))].filter(Boolean)
    .map((p) => ({ name: `${p.name} = 100`, parameter: p.id, value: 100, expectedHex: ['B0', hex(recipes.get(p.messageRecipe).controller), hex(100)].join(' ') }));
  const doc = data.source;
  return {
    schemaVersion: 1,
    profileVersion: layout.profileVersion ?? '0.1.0',
    minCEditorVersion: '0.9.0',
    id: layout.id,
    name: layout.name,
    manufacturer: 'Kodamo',
    family: layout.family,
    status: 'experimental',
    trust: 'local',
    description: layout.description,
    sources: [{ type: 'manual', title: doc.title, notes: `The MIDI implementation (PDF pages ${doc.pages[0]} - ${doc.pages[1]}), read by tools/profiles/kodamo/read-kodamo-manual.mjs from ${doc.file} (sha256 ${doc.sha256}), ${doc.url}, linked from ${doc.linkedFrom}. Not yet checked against the instrument itself.` }],
    testedWith: [],
    authoringNotes: [
      'Generated by tools/profiles/kodamo/make-profiles.mjs; edit the layout in tools/profiles/kodamo/synths/, not this file.',
      'Every parameter is a controller the manual maps to a voice parameter, sent 0 - 127 on the channel variable: the MASK1 listens on four channels from its Base MIDI Channel, the voice on the first being the one the keyboard plays, so the channel variable picks the part. Nothing here has been sent to a real instrument yet.',
      'The manual gives no values for the settings that are lists (filter MODE, LFO WAVE and DEST, play MODE, FX and arp TYPE): they are sent 0 - 127, as printed. The mask\'s 512 values are four controllers, a quarter each, as the manual lays them out.',
      'Kodamo\'s firmware notes add controllers this manual does not list (CC 16, 17 and 58 - 63 among them, "check the updated user manual"); they are not laid out.',
      `Left out, and named: ${left.join(', ')}.`,
    ],
    variables: { channel: 1 },
    coverage: {
      singleParameterWrite: `complete-for-the-manual's-controllers: ${parameters.length} parameters`,
      realtimeEditing: 'complete-for-the-manual\'s-controllers',
      editBufferDumpRequest: 'notImplemented',
      editBufferDumpParse: 'notImplemented: the manual lists its SysEx messages without their format',
      bankDump: 'notImplemented',
      inboundControllers: 'notImplemented',
      verifiedOnHardware: false,
    },
    timing: { minDelayBetweenMessagesMs: 0 },
    messageRecipes: [...recipes.values()],
    parameters,
    tests,
  };
}

export { stringifyProfile };
