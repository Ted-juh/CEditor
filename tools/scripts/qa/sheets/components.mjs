// components.mjs — QA-01: one of every component type, at its authored defaults.
//
// What this sheet is for: the cheapest possible answer to "did anything stop rendering". Every
// component the editor can make, on one screen, captioned, in a fixed order. You open it, you
// look, and anything blank or wrong is the thing to fix. No clicking, no setup, no device.
//
// What makes it worth generating rather than drawing once: it is built from COMPONENT_TYPES, so
// the sheet cannot fall behind the model. Add a component and it appears here on the next
// regeneration — and until you file it under a group below, `qaPanels.test.js` fails. That is the
// whole point. A checklist that has to be updated by hand is a checklist that is already wrong.
//
// Defaults ON PURPOSE. This sheet asks "does the authored default look right", which is the state
// a user meets first and the one nobody ever checks. Non-default property work is QA-02's job.

