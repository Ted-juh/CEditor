const NOTES = `QA-01 — every component type at its authored defaults.

Generated by tools/scripts/qa/make-qa-panels.mjs. Do not hand-edit: regenerate instead, or your
changes vanish the next time a component is added.

How to read it
  Each control sits under a caption naming its type. Everything here is at the default a user
  gets when they drag the component onto a blank canvas — nothing is configured.

What a failure looks like
  - a blank cell                      the renderer threw, or draws nothing at defaults
  - a control the size of its caption  the type's defaultOverrides lost its Transform
  - text reading "Label" or "Button"   correct: that IS the authored default
  - a cell that overlaps its neighbour the component ignores its Transform width/height

What this sheet does NOT prove
  Nothing here is interactive, bound, or scripted. A component can render perfectly at defaults
  and still be broken the moment it is dragged, bound to a device, or driven from a script.
  That is QA-03 through QA-06.`;

export function buildComponentsSheet() {
  const panel = createPanel('QA-01 Components');

  const groups = GROUPS.map((group) => ({
    title: group.title,
    cells: group.types.map((type) => ({
      caption: type,
      // A stable id per type, so a diff between two regenerations is a real change rather than
      // a renumbering. Same reason the sheet is committed at all.
      control: createControl(type, { Core: { id: `qa01_${type}`, name: `qa01_${type}` } }),
    })),
  }));

  const { controls, height } = flowGroups(groups);
  panel.controls = controls;
  panel.height = height;

  return styleSheet(panel, { title: 'QA-01 — every component type at authored defaults', notes: NOTES });
}

/** Every type this sheet places. Used by the coverage ratchet. */
export function coveredTypes() {
  return GROUPS.flatMap((group) => group.types);
}

/** Declared so the test can compare against the model rather than against a copy of it. */
export function allTypes() {
  return Object.keys(COMPONENT_TYPES);
}
