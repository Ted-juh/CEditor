// generate-google-icon-names.mjs — refresh the list of Google's icon names (Material Symbols).
//
// Settings → Icons searches this list to offer Google's icons by name. The list is baked into the
// app, not fetched at run time, because the only machine-readable index Google publishes on
// fonts.google.com is not meant for other sites to read; the names themselves are in Google's own
// repository, one per line, beside the code point of each glyph. Every icon in the list is fetched
// from fonts.gstatic.com when somebody adds it (utils/googleIcons.js) — that part is live.
//
// An icon Google adds after this list was made can still be added: Settings → Icons offers to try
// any name typed in full. Run this now and then to bring the list up to date; it needs network.
//
//   Regenerate: npm run gen:google-icons   (in CE/web)
//   Output:     src/CE_Application/generated/googleIconNames.js

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUT = resolve(HERE, '../src/CE_Application/generated/googleIconNames.js');

// The Outlined, Rounded and Sharp sets share one list of names; Outlined's is read.
export const SOURCE_URL = 'https://raw.githubusercontent.com/google/material-design-icons/master/'
  + 'variablefont/MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints';

/** The names in a .codepoints file — `name codepoint` per line — unique and sorted. */
export function parseCodepoints(text) {
  const names = new Set();
  for (const line of String(text ?? '').split(/\r?\n/)) {
    const name = line.trim().split(/\s+/)[0];
    if (name && /^[a-z0-9_]+$/.test(name)) names.add(name);
  }
  return [...names].sort();
}

export function renderModule(names, fetchedOn) {
  return `// GENERATED by scripts/generate-google-icon-names.mjs — do not edit.
// The names of Google's icons (Material Symbols), from github.com/google/material-design-icons,
// fetched ${fetchedOn}. Regenerate with \`npm run gen:google-icons\` in CE/web.

export const GOOGLE_ICON_NAMES_FETCHED = ${JSON.stringify(fetchedOn)};

export const GOOGLE_ICON_NAMES = ${JSON.stringify(names)};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`could not fetch the icon list: HTTP ${response.status}`);
  const names = parseCodepoints(await response.text());
  if (names.length < 1000) throw new Error(`only ${names.length} names — the source format may have changed`);
  writeFileSync(OUT, renderModule(names, new Date().toISOString().slice(0, 10)));
  console.log(`wrote ${names.length} icon names to ${OUT}`);
}
