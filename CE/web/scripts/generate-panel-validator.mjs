// generate-panel-validator.mjs — compile the panel document schema into a plain module.
//
// utils/panelDocumentSchema.js is the source; this writes the validator Ajv would build from it at
// run time, as code, so the editor and the player run it without shipping Ajv's compiler (and
// without compiling the schema on every start). Ajv's "standalone" mode is made for this.
//
// Same contract as the help bundle: the output is committed, and test/panelFormat.test.js
// regenerates it in memory and fails when the committed file differs.
//
//   Regenerate: npm run gen:panel-validator
//   Output:     src/CE_Application/generated/panelDocumentValidator.js

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { PANEL_DOCUMENT_SCHEMA } from '../src/CE_Application/utils/panelDocumentSchema.js';

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUT = resolve(HERE, '../src/CE_Application/generated/panelDocumentValidator.js');

export function buildPanelValidatorSource() {
  // allErrors: report every problem in a document, not the first — a person fixing a file by hand
  // wants the list. strict: the schema is ours, so a typo in it should fail here, not pass silently.
  const ajv = new Ajv({ allErrors: true, strict: true, allowUnionTypes: true, code: { source: true, esm: true } });
  const validate = ajv.compile(PANEL_DOCUMENT_SCHEMA);
  const body = standaloneCode(ajv, validate);
  return `// GENERATED by scripts/generate-panel-validator.mjs from utils/panelDocumentSchema.js — do not edit.\n`
    + `// Regenerate with \`npm run gen:panel-validator\`.\n/* eslint-disable */\n${body}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, buildPanelValidatorSource());
  console.log(`wrote ${OUT}`);
}
