// Vertical eighth-blocks fill from the bottom; left-blocks fill from the left.
const VERT_BLOCKS = '▁▂▃▄▅▆▇█';
const LEFT_BLOCKS = '▏▎▍▌▋▊▉';

function blockGlyph(ch) {
  const vi = VERT_BLOCKS.indexOf(ch);
  if (vi >= 0) {
    const fillRows = Math.max(1, Math.round(((vi + 1) * FONT_H) / 8));
    return Array.from({ length: FONT_H }, (_, r) => (r >= FONT_H - fillRows ? '#####' : '.....'));
  }
  const li = LEFT_BLOCKS.indexOf(ch);
  if (li >= 0) {
    const fillCols = Math.max(1, Math.round(((li + 1) * FONT_W) / 7));
    const row = '#'.repeat(fillCols) + '.'.repeat(FONT_W - fillCols);
    return Array.from({ length: FONT_H }, () => row);
  }
  return null;
}

// Rows of a character's glyph (7 strings of 5), or null when unknown.
export function glyphRows(ch) {
  const c = String(ch ?? ' ');
  return GLYPHS[c] ?? GLYPHS[c.toUpperCase()] ?? GLYPHS[c.toLowerCase()] ?? blockGlyph(c);
}

// Stamp one character into a row-major 1-bit target at (x, y), scaled by an
// integer factor. Pixels outside the target (or the optional clip box) are
// dropped. Returns true if the character was known.
export function drawCharInto(target, tw, th, ch, x, y, scaleFactor = 1, clip = null) {
  const rows = glyphRows(ch);
  if (!rows) return false;
  const s = Math.max(1, Math.round(scaleFactor));
  for (let gy = 0; gy < FONT_H; gy += 1) {
    const row = rows[gy];
    for (let gx = 0; gx < FONT_W; gx += 1) {
      if (row[gx] !== '#') continue;
      for (let sy = 0; sy < s; sy += 1) {
        for (let sx = 0; sx < s; sx += 1) {
          const px = x + gx * s + sx;
          const py = y + gy * s + sy;
          if (px < 0 || px >= tw || py < 0 || py >= th) continue;
          if (clip && (px < clip.x0 || px > clip.x1 || py < clip.y0 || py > clip.y1)) continue;
          target[py * tw + px] = 1;
        }
      }
    }
  }
  return true;
}

// Stamp a string. align: left | center | right within `boxW` (0 = no box:
// anchor at x). When boxW > 0 it also clips horizontally. Returns the text's
// pixel width.
export function drawTextInto(target, tw, th, text, x, y, scaleFactor = 1, align = 'left', boxW = 0) {
  const s = Math.max(1, Math.round(scaleFactor));
  const str = String(text ?? '');
  const advance = FONT_ADVANCE * s;
  const textW = str.length > 0 ? str.length * advance - s : 0;
  let startX = x;
  if (boxW > 0) {
    if (align === 'center') startX = x + Math.round((boxW - textW) / 2);
    else if (align === 'right') startX = x + boxW - textW;
  }
  const clip = boxW > 0 ? { x0: x, x1: x + boxW - 1, y0: y, y1: y + FONT_H * s - 1 + s } : null;
  for (let i = 0; i < str.length; i += 1) {
    drawCharInto(target, tw, th, str[i], startX + i * advance, y, s, clip);
  }
  return textW;
}
