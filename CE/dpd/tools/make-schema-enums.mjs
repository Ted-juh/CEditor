// make-schema-enums.mjs — the value lists of dpd.schema.json, written out for the validator.
//
//   node CE/dpd/tools/make-schema-enums.mjs           # rewrite tools/schema-enums.mjs
//   node CE/dpd/tools/make-schema-enums.mjs --check   # fail if it no longer matches the schema
//
// validate.mjs is the dependency-free check the tools and the Designer run, and it kept its own
// copies of the schema's enums (value types, wire messages, encodings, checksum types, ...): two
// lists for each, kept in step by hand. Now the schema is the one place a value is allowed, and this
// writes what the validator imports from it. A browser-safe module rather than an import of the
// JSON, which the Designer's copy of the validator (generated/dpd, emit-library.mjs) could not make.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SCHEMA = join(HERE, '..', 'dpd.schema.json');
const OUT = join(HERE, 'schema-enums.mjs');

const schema = JSON.parse(readFileSync(SCHEMA, 'utf8'));
const at = (path) => {
  let node = schema;
  for (const key of path.split('/').filter(Boolean)) node = node?.[key];
  if (!Array.isArray(node?.enum)) throw new Error(`dpd.schema.json: no enum at ${path}`);
  return node.enum;
};

// Each list the validator checks, by where the schema allows its values.
const LISTS = {
  KINDS: '/properties/kind',
  BYTE_ORDERS: '/properties/byteOrder',
  COMPLETENESS: '/properties/completeness',
  VALUE_TYPES: '/$defs/parameter/properties/valueType',
  WIRE_DIRS: '/$defs/wire/properties/dir',
  WIRE_MSGS: '/$defs/wire/properties/msg',
  CHECKSUM_TYPES: '/$defs/checksum/properties/type',
  SHAPE_KINDS: '/$defs/messageShape/properties/kind',
  SCOPE_KINDS: '/$defs/scope/properties/kind',
  DUMP_KINDS: '/$defs/dump/properties/kind',
  PARAM_ENCODING_TYPES: '/$defs/encoding/properties/type',
  DUMP_CODEC_TYPES: '/$defs/dumpLayoutEntry/properties/codec/properties/type',
  RECORD_FIELD_TYPES: '/$defs/dump/properties/message/properties/payload/properties/records/properties/keyType',
  DISPLAY_FORMATS: '/$defs/parameterDisplay/properties/format',
  PRESET_BANK_ROLES: '/$defs/presetBank/properties/role',
  PRESET_RECALL_KINDS: '/$defs/presetRecall/properties/kind',
  PROVENANCE_SOURCES: '/$defs/provenance/properties/source',
};

const text = [
  '// schema-enums.mjs — GENERATED by make-schema-enums.mjs from dpd.schema.json; do not edit by hand.',
  '// The values the schema allows, for validate.mjs: `node CE/dpd/tools/make-schema-enums.mjs`.',
  ...Object.entries(LISTS).map(([name, path]) => `export const ${name} = ${JSON.stringify(at(path))}; // ${path}`),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (now !== text) {
    console.error('CE/dpd/tools/schema-enums.mjs is out of date with dpd.schema.json: run node CE/dpd/tools/make-schema-enums.mjs');
    process.exit(1);
  }
  console.log('schema-enums.mjs is up to date.');
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote ${OUT}: ${Object.keys(LISTS).length} lists`);
}
